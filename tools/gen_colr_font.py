#!/usr/bin/env python3
"""Generates tests/colr_fixture.h: a small TrueType font with a COLR table (v1 glyphs, and one v0), for tests/colr_test.c.

Units per em 1000; every color glyph is drawn on the square 0..1000 (y up). Palette 0 (marked for light backgrounds): 0 red, 1 blue,
2 yellow, 3 gray (#808080); palette 1 (marked for dark backgrounds) is the same with 0 green.
  A  layers: the left half red, the right half blue at half alpha
  B  a linear gradient red -> blue, p0 (0,0) p1 (1000,1000) p2 (0,1000): projected, it runs along x
  C  a radial gradient red -> blue from (500,500) r 0 to r 500, padded; has a clip box (the square)
  D  a sweep gradient red -> blue around (500,500), 0 to 360 degrees
  E  the left half, red, rotated 90 degrees around (500,500): the bottom half
  F  a red square with a blue circle (r 300 at 500,500) cut out of it (composite dest-out)
  G  a yellow square multiplied by a gray one (composite multiply): #808000
  H  a red bar (x 0..200) skewed 45 degrees along x around (0,0): its top leans left to x -1000..-800
  Z  no color glyph: its outline
  V  a COLRv0 glyph: layers, the left half red and the right half blue
  W  layers: the left half in the foreground (text) color, the right half red
Needs fontTools."""
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.colorLib.builder import buildCOLR, buildCPAL, ColorPaletteType
from fontTools.ttLib.tables import otTables as ot
import io, math, sys

def rect(x0, y0, x1, y1):
    p = TTGlyphPen(None)
    p.moveTo((x0, y0)); p.lineTo((x0, y1)); p.lineTo((x1, y1)); p.lineTo((x1, y0)); p.closePath()
    return p.glyph()

def circle(cx, cy, r):
    p = TTGlyphPen(None)
    pts = [(cx + r * math.cos(a * math.pi / 32), cy + r * math.sin(a * math.pi / 32)) for a in range(64)]
    p.moveTo(tuple(map(round, pts[0])))
    for q in pts[1:]:
        p.lineTo(tuple(map(round, q)))
    p.closePath()
    return p.glyph()

colors = 'ABCDEFGHZVW'
names = ['.notdef'] + list(colors) + ['sq', 'left', 'right', 'disc', 'bar']
glyphs = {n: rect(0, 0, 1000, 1000) for n in names}
glyphs.update(left=rect(0, 0, 500, 1000), right=rect(500, 0, 1000, 1000), disc=circle(500, 500, 300), bar=rect(0, 0, 200, 1000))

fb = FontBuilder(1000, isTTF=True)
fb.setupGlyphOrder(names)
fb.setupCharacterMap({ord(c): c for c in colors})
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics({n: (1000, getattr(fb.font['glyf'][n], 'xMin', 0)) for n in names})  # (an lsb that is not xMin moves the outline)
fb.setupHorizontalHeader(ascent=1000, descent=-200)
fb.setupNameTable({'familyName': 'GpColrTest', 'styleName': 'Regular'})
fb.setupOS2(sTypoAscender=1000, sTypoDescender=-200, usWinAscent=1000, usWinDescent=200)
fb.setupPost()

F = ot.PaintFormat
def solid(i, a=1.0):
    return {'Format': F.PaintSolid, 'PaletteIndex': i, 'Alpha': a}
def glyph(g, paint):
    return {'Format': F.PaintGlyph, 'Glyph': g, 'Paint': paint}
line = {'Extend': 'pad', 'ColorStop': [{'StopOffset': 0, 'PaletteIndex': 0, 'Alpha': 1}, {'StopOffset': 1, 'PaletteIndex': 1, 'Alpha': 1}]}
paints = {
    'A': {'Format': F.PaintColrLayers, 'Layers': [glyph('left', solid(0)), glyph('right', solid(1, 0.5))]},
    'B': glyph('sq', {'Format': F.PaintLinearGradient, 'ColorLine': line, 'x0': 0, 'y0': 0, 'x1': 1000, 'y1': 1000, 'x2': 0, 'y2': 1000}),
    'C': glyph('sq', {'Format': F.PaintRadialGradient, 'ColorLine': line, 'x0': 500, 'y0': 500, 'r0': 0, 'x1': 500, 'y1': 500, 'r1': 500}),
    'D': glyph('sq', {'Format': F.PaintSweepGradient, 'ColorLine': line, 'centerX': 500, 'centerY': 500, 'startAngle': 0, 'endAngle': 360}),
    'E': {'Format': F.PaintRotateAroundCenter, 'angle': 90, 'centerX': 500, 'centerY': 500, 'Paint': glyph('left', solid(0))},
    'F': {'Format': F.PaintComposite, 'CompositeMode': 'dest_out', 'SourcePaint': glyph('disc', solid(1)), 'BackdropPaint': glyph('sq', solid(0))},
    'G': {'Format': F.PaintComposite, 'CompositeMode': 'multiply', 'SourcePaint': glyph('sq', solid(3)), 'BackdropPaint': glyph('sq', solid(2))},
    'V': [('left', 0), ('right', 1)],  # (a list of layers: COLRv0)
    'W': {'Format': F.PaintColrLayers, 'Layers': [glyph('left', solid(0xFFFF)), glyph('right', solid(0))]},
    'H': {'Format': F.PaintSkew, 'xSkewAngle': 45, 'ySkewAngle': 0, 'Paint': glyph('bar', solid(0))},
}
fb.font['COLR'] = buildCOLR(paints, clipBoxes={'C': (0, 0, 1000, 1000)})
rest = [(0, 0, 1, 1), (1, 1, 0, 1), (128 / 255, 128 / 255, 128 / 255, 1)]
fb.font['CPAL'] = buildCPAL([[(1, 0, 0, 1)] + rest, [(0, 1, 0, 1)] + rest],
                            paletteTypes=[ColorPaletteType.USABLE_WITH_LIGHT_BACKGROUND, ColorPaletteType.USABLE_WITH_DARK_BACKGROUND])
buf = io.BytesIO()
fb.font.save(buf)
data = buf.getvalue()
out = ['/* Generated by tools/gen_colr_font.py: a TrueType font with a COLR table (see there). */', 'static const unsigned char fx_colrfont[] = {']
for i in range(0, len(data), 16):
    out.append('    ' + ' '.join('0x%02x,' % b for b in data[i:i + 16]))
out.append('};')
open(sys.argv[1] if len(sys.argv) > 1 else 'tests/colr_fixture.h', 'w').write('\n'.join(out) + '\n')
