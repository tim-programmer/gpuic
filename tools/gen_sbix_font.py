#!/usr/bin/env python3
"""Generates tests/sbix_fixture.h: a small TrueType font with an 'sbix' table (Apple's bitmap emoji format), for tests/colr_test.c.

Units per em 1000. 'A' has a square outline (0..1000) and, in one 64 ppem strike, a 64 x 64 PNG: the left half red, the right half blue,
placed on the baseline. Drawn from its outline it would be a plain square. Needs fontTools."""
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import newTable
from fontTools.ttLib.tables.sbixStrike import Strike
from fontTools.ttLib.tables.sbixGlyph import Glyph
import io, struct, sys, zlib

def png(w, h, pixel):
    def chunk(tag, data):
        return struct.pack('>I', len(data)) + tag + data + struct.pack('>I', zlib.crc32(tag + data) & 0xffffffff)
    rows = b''.join(b'\0' + b''.join(bytes(pixel(x, y)) for x in range(w)) for y in range(h))
    return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 6, 0, 0, 0)) + chunk(b'IDAT', zlib.compress(rows)) + chunk(b'IEND', b'')

def square():
    p = TTGlyphPen(None)
    p.moveTo((0, 0)); p.lineTo((0, 1000)); p.lineTo((1000, 1000)); p.lineTo((1000, 0)); p.closePath()
    return p.glyph()

names = ['.notdef', 'A']
fb = FontBuilder(1000, isTTF=True)
fb.setupGlyphOrder(names)
fb.setupCharacterMap({ord('A'): 'A'})
fb.setupGlyf({n: square() for n in names})
fb.setupHorizontalMetrics({n: (1000, 0) for n in names})
fb.setupHorizontalHeader(ascent=1000, descent=-200)
fb.setupNameTable({'familyName': 'GpSbixTest', 'styleName': 'Regular'})
fb.setupOS2(sTypoAscender=1000, sTypoDescender=-200, usWinAscent=1000, usWinDescent=200)
fb.setupPost()

strike = Strike(ppem=64, resolution=72)
strike.glyphs['A'] = Glyph(glyphName='A', graphicType='png ', imageData=png(64, 64, lambda x, y: (255, 0, 0, 255) if x < 32 else (0, 0, 255, 255)))
sbix = newTable('sbix')
sbix.strikes[64] = strike
fb.font['sbix'] = sbix
buf = io.BytesIO()
fb.font.save(buf)
data = buf.getvalue()
out = ['/* Generated by tools/gen_sbix_font.py: a TrueType font with an sbix table (see there). */', 'static const unsigned char fx_sbixfont[] = {']
for i in range(0, len(data), 16):
    out.append('    ' + ' '.join('0x%02x,' % b for b in data[i:i + 16]))
out.append('};')
open(sys.argv[1] if len(sys.argv) > 1 else 'tests/sbix_fixture.h', 'w').write('\n'.join(out) + '\n')
