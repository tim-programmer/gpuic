#!/usr/bin/env python3
"""Generates src/grapheme_data.h (the Unicode properties that decide where a grapheme cluster ends, UAX #29 with the Indic conjunct
rule) and tests/grapheme_cases.inc (strings with the cluster boundaries the `regex` module's \\X finds) from the `regex` module, which
carries the Unicode data and its own implementation of the segmentation rules. The library has its own implementation of the rules
(src/text.c); the test compares the two.

    tools/gen_grapheme.py            writes both files
    tools/gen_grapheme.py --check    exits 1 if they are not what this would write
"""
import os, random, sys
import regex

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def ranges(pat):
    r = regex.compile(pat)
    out, start = [], None
    for cp in range(0x110000):
        ok = not (0xD800 <= cp <= 0xDFFF) and bool(r.fullmatch(chr(cp)))
        if ok and start is None:
            start = cp
        if not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    return out

TABLES = [
    ("extend", r"\p{Grapheme_Cluster_Break=Extend}"),
    ("spacing", r"\p{Grapheme_Cluster_Break=SpacingMark}"),
    ("prepend", r"\p{Grapheme_Cluster_Break=Prepend}"),
    ("control", r"[\p{Grapheme_Cluster_Break=Control}\p{Grapheme_Cluster_Break=CR}\p{Grapheme_Cluster_Break=LF}]"),
    ("extpict", r"\p{Extended_Pictographic}"),
    ("consonant", r"\p{InCB=Consonant}"),
    ("linker", r"\p{InCB=Linker}"),
]

def data_header():
    lines = ["/* Generated by tools/gen_grapheme.py: do not edit. Unicode data from the `regex` module. */\n",
             "/* Sorted, inclusive ranges of the codepoints that have each grapheme-break property. */\n"]
    for name, pat in TABLES:
        rs = ranges(pat)
        lines.append("static const uint32_t gb_%s[][2] = {\n" % name)
        row = []
        for a, b in rs:
            row.append("{0x%x,0x%x}," % (a, b))
            if len(row) == 6:
                lines.append("    " + "".join(row) + "\n")
                row = []
        if row:
            lines.append("    " + "".join(row) + "\n")
        lines.append("};\n")
    return "".join(lines)

# an alphabet of everything that matters to the rules, for random strings
ALPHABET = (
    list("ab1 .") + ["\u00e9", "e\u0301"[1:], "\u0308", "\u200d", "\u200c", "\u20e3", "\ufe0f", "\ufe0e"]
    + ["\U0001f468", "\U0001f469", "\U0001f467", "\U0001f3fb", "\u2764", "\u263a", "\U0001f1fa", "\U0001f1f8", "\U0001f1eb", "\U0001f1f7", "\U000e0067", "\U000e007f"]
    + ["\u1100", "\u1101", "\u1112", "\u1161", "\u1175", "\u11a8", "\u11c2", "\uac00", "\uac01", "\uac1c", "\uac1b", "\ud55c", "\ud7b0", "\ud7cb"]
    + ["\u0915", "\u0937", "\u0924", "\u0930", "\u092f", "\u094d", "\u093c", "\u093f", "\u0902", "\u0905", "\u0903"]            # Devanagari
    + ["\u0995", "\u09b7", "\u09cd", "\u09be"] + ["\u0a95", "\u0ab7", "\u0acd"] + ["\u0b15", "\u0b4d"] + ["\u0c15", "\u0c37", "\u0c4d"]
    + ["\u0d15", "\u0d37", "\u0d4d", "\u0d3e", "\u0d4e"]                                                                      # Bengali .. Malayalam
    + ["\u0b95", "\u0bcd", "\u0bb7"] + ["\u0c95", "\u0ccd"] + ["\u0a15", "\u0a4d"]                                           # Tamil, Kannada, Gurmukhi: no conjunct rule
    + ["\u0600", "\u06dd", "\u0627", "\u0300", "\u0301", "\u0e01", "\u0e31", "\u0e33", "\u4e2d", "\n"]
)

def cases():
    fixed = ["", "a", "abc", "e\u0301x", "\u0915\u094d\u0937", "\u0915\u094d", "\u0915\u094da", "\u0915\u093f", "\u0905\u094d\u0915", "\u0924\u094d\u0930\u094d\u092f",
             "\u0915\u093c\u094d\u0937", "\u0b95\u0bcd\u0bb7", "\u0995\u09cd\u09b7", "\u0d15\u0d4d\u0d37", "\u1112\u1161\u11ab", "\u1100\u1100\u1161\u11a8",
             "\u1161\u1100", "\uac01\u11a8", "\uac00\u1161", "\uac1c\u1161", "\uac1b\u1161", "\uac1b\u11a8", "\ud55c\uad6d\uc5b4", "\U0001f468\u200d\U0001f469\u200d\U0001f467", "a\u200db", "\U0001f1fa\U0001f1f8\U0001f1eb\U0001f1f7",
             "\U0001f1fa\U0001f1f8\U0001f1eb", "\u0600a", "\u0600\u0600a", "\u2764\ufe0f\u200d\U0001f525", "\U0001f3fb", "\U0001f44d\U0001f3fd", "a\u0308\u0308b"]
    rng = random.Random(29)
    rand = ["".join(rng.choice(ALPHABET) for _ in range(rng.randint(1, 9))) for _ in range(900)]
    return fixed + rand

def cluster_ends(s):
    ends, at = [], 0
    for m in regex.finditer(r"\X", s):
        at += len(m.group(0).encode("utf-8"))
        ends.append(at)
    return ends

def cases_inc():
    out = ["/* Generated by tools/gen_grapheme.py: do not edit. A string, and where each grapheme cluster of it ends (byte offsets), by regex's \\X. */\n"]
    for s in cases():
        b = s.encode("utf-8")
        lit = "".join("\\x%02x" % c for c in b)
        ends = cluster_ends(s)
        out.append('{ "%s", %d, %d, { %s } },\n' % (lit, len(b), len(ends), ", ".join(str(e) for e in ends) if ends else "0"))
    return "".join(out)

if __name__ == "__main__":
    files = [(os.path.join(ROOT, "src/grapheme_data.h"), data_header()), (os.path.join(ROOT, "tests/grapheme_cases.inc"), cases_inc())]
    if "--check" in sys.argv:
        for path, text in files:
            cur = open(path).read() if os.path.exists(path) else ""
            if cur != text:
                sys.stderr.write("%s is out of date: run tools/gen_grapheme.py\n" % os.path.basename(path))
                sys.exit(1)
        sys.exit(0)
    for path, text in files:
        open(path, "w").write(text)
        print("wrote", path, len(text.splitlines()), "lines")
