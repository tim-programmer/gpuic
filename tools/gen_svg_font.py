#!/usr/bin/env python3
"""Generates tests/svgfont_fixture.h: a small TrueType font with an 'SVG ' table, for tests/svgfont_test.c.

Units per em 1000, ascender 800. 'A' (glyph 1) and 'B' (glyph 2) have square outlines (what a renderer without SVG would draw) and color
glyphs in ONE shared SVG document: A is red on its left half and blue on its right (x 0..300 and 300..600, y -800..0, y down from the
baseline); B is a green square cut by a circle clip of radius 300 at (300, -400), drawn through a <use> of a shape in <defs>.
'C' (glyph 3) has no SVG glyph. Needs fontTools."""
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import newTable
import io, sys

def square():
    p = TTGlyphPen(None)
    p.moveTo((0, 0)); p.lineTo((0, 800)); p.lineTo((600, 800)); p.lineTo((600, 0)); p.closePath()
    return p.glyph()

fb = FontBuilder(1000, isTTF=True)
names = ['.notdef', 'A', 'B', 'C']
fb.setupGlyphOrder(names)
fb.setupCharacterMap({0x41: 'A', 0x42: 'B', 0x43: 'C'})
fb.setupGlyf({n: square() for n in names})
fb.setupHorizontalMetrics({n: (600, 0) for n in names})
fb.setupHorizontalHeader(ascent=800, descent=-200)
fb.setupNameTable({'familyName': 'GpSvgTest', 'styleName': 'Regular'})
fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, usWinAscent=800, usWinDescent=200)
fb.setupPost()
doc = ('<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink">'
       '<defs><clipPath id="c"><circle cx="300" cy="-400" r="300"/></clipPath><rect id="sq" y="-800" width="600" height="800" fill="#00ff00"/></defs>'
       '<g id="glyph1"><rect y="-800" width="300" height="800" fill="#ff0000"/><rect x="300" y="-800" width="300" height="800" fill="#0000ff"/></g>'
       '<g id="glyph2" clip-path="url(#c)"><use xlink:href="#sq"/></g></svg>')
svg = newTable('SVG ')
svg.docList = [(doc, 1, 2)]
fb.font['SVG '] = svg
buf = io.BytesIO()
fb.font.save(buf)
data = buf.getvalue()
out = ['/* Generated by tools/gen_svg_font.py: a TrueType font with an SVG table (see there). */', 'static const unsigned char fx_svgfont[] = {']
for i in range(0, len(data), 16):
    out.append('    ' + ' '.join('0x%02x,' % b for b in data[i:i + 16]))
out.append('};')
open(sys.argv[1] if len(sys.argv) > 1 else 'tests/svgfont_fixture.h', 'w').write('\n'.join(out) + '\n')
